/**
 * The board's text in English and Simplified Chinese. The host reports the
 * user's locale; "auto" follows it, and the board page lets the user override
 * that choice. Ticket content, statuses, skill commands and git commit
 * messages are data, not UI text, and are never translated.
 */
export type Language = 'en' | 'zh';
export type LanguagePreference = 'auto' | Language;

export const asLanguagePreference = (value: unknown): LanguagePreference =>
  value === 'en' || value === 'zh' ? value : 'auto';

export const resolveLanguage = (preference: LanguagePreference, locale: string | undefined): Language => {
  if (preference === 'en' || preference === 'zh') return preference;
  return /^zh(?:[-_]|$)/i.test((locale ?? '').trim()) ? 'zh' : 'en';
};

