const DICTIONARIES: Record<Language, Record<TranslationKey, string>> = { en: EN, zh: ZH };

export type TranslationValues = Record<string, string | number>;

export type Translator = (key: TranslationKey, values?: TranslationValues) => string;

const interpolate = (text: string, values?: TranslationValues): string =>
  values
    ? text.replace(/\{(\w+)\}/g, (match, name: string) => {
        const value = values[name];
        return value === undefined ? match : String(value);
      })
    : text;

export const translate = (language: Language, key: TranslationKey, values?: TranslationValues): string =>
  interpolate(DICTIONARIES[language][key], values);

export const translator = (language: Language): Translator =>
  (key, values) => translate(language, key, values);
